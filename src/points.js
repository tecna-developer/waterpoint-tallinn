// Как точка называется и где находится — с точки зрения пользователя, а не источника.
// Вынесено из main.js: логика ветвится по категории и языку, а проверить её раньше можно
// было только переключая язык в браузере и разглядывая карточки.
import { t, getLang } from './i18n.js';

// У кранов имя одно на все языки — это адрес. У туалетов источник даёт локализованные
// названия, но не для всех точек и не на всех языках, поэтому нужна цепочка запасных
// вариантов: язык интерфейса → эстонский оригинал → общее «Общественный туалет».
export function pointName(p) {
  if (!p) return '';
  if (p.category !== 'public_toilet') return p.name;
  const lang = getLang();
  const localized = lang === 'en' ? p.name_en : lang === 'ru' ? p.name_ru : null;
  return localized || p.name || t('toilet_unnamed');
}

// Район города и микрорайон: у части точек нет ни того, ни другого, и пустые разделители
// в интерфейсе выглядят как ошибка вёрстки.
export function pointPlace(p) {
  return [p?.asum, p?.district].filter(Boolean).join(', ');
}
