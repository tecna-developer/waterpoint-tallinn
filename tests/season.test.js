import { describe, it, expect } from 'vitest';
import { inSeason } from '../src/data.js';

// Сезон питьевых кранов Tallinna Vesi — 1 мая по 31 октября (§5 ТЗ). Проверяем прежде
// всего границы: именно они молча ломаются, если сравнение перепутать со строгим.
const кран = { seasonal_from: { m: 5, d: 1 }, seasonal_to: { m: 10, d: 31 } };
const дата = (г, м, д) => new Date(г, м - 1, д, 12, 0, 0);

describe('inSeason', () => {
  it('первый день сезона — уже в сезоне', () => {
    expect(inSeason(кран, дата(2026, 5, 1))).toBe(true);
  });

  it('последний день сезона — ещё в сезоне', () => {
    expect(inSeason(кран, дата(2026, 10, 31))).toBe(true);
  });

  it('день до начала сезона — вне сезона', () => {
    expect(inSeason(кран, дата(2026, 4, 30))).toBe(false);
  });

  it('день после конца сезона — вне сезона', () => {
    expect(inSeason(кран, дата(2026, 11, 1))).toBe(false);
  });

  it('середина лета — в сезоне', () => {
    expect(inSeason(кран, дата(2026, 7, 15))).toBe(true);
  });

  it('январь — вне сезона', () => {
    expect(inSeason(кран, дата(2026, 1, 15))).toBe(false);
  });

  // Границы месяцев внутри сезона: проверяем, что сравниваются пары (месяц, день),
  // а не только месяцы — иначе 1 мая и 31 октября считались бы по-разному.
  it('30 апреля и 1 ноября — по разные стороны от сезона', () => {
    expect(inSeason(кран, дата(2026, 4, 30))).toBe(false);
    expect(inSeason(кран, дата(2026, 11, 1))).toBe(false);
    expect(inSeason(кран, дата(2026, 5, 2))).toBe(true);
    expect(inSeason(кран, дата(2026, 10, 30))).toBe(true);
  });
});
